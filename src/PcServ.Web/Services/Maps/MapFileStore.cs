namespace PcServ.Web.Services.Maps;

/// <summary>
/// Keeps map files in the data folder, outside the public web root, so they can only be
/// reached through a signed-in endpoint. Folder names are generated here, never taken from users.
/// </summary>
public sealed class MapFileStore(string dataDirectory)
{
    private const string BaseImageName = "base.png";

    private readonly string _root = Path.Combine(dataDirectory, "maps");

    public static string NewStorageKey() => Guid.NewGuid().ToString("N");

    public async Task SaveAsync(string storageKey, string sourceFileName, byte[] source, byte[] baseImage)
    {
        var folder = FolderFor(storageKey);
        Directory.CreateDirectory(folder);

        // The original is kept under a fixed name. It's the starting point for PDF export.
        var extension = Path.GetExtension(sourceFileName).ToLowerInvariant();
        await File.WriteAllBytesAsync(Path.Combine(folder, "source" + extension), source);
        await File.WriteAllBytesAsync(Path.Combine(folder, BaseImageName), baseImage);
    }

    /// <summary>The original uploaded PDF, or null if there isn't one.</summary>
    public string? SourcePdfPath(string storageKey)
    {
        var path = Path.Combine(FolderFor(storageKey), "source.pdf");
        return File.Exists(path) ? path : null;
    }

    public Task ReplaceBaseImageAsync(string storageKey, byte[] baseImage) =>
        File.WriteAllBytesAsync(Path.Combine(FolderFor(storageKey), BaseImageName), baseImage);

    public async Task SavePhotoAsync(string mapKey, string photoKey, byte[] photo, byte[] thumbnail)
    {
        var folder = PhotoFolder(mapKey);
        Directory.CreateDirectory(folder);
        await File.WriteAllBytesAsync(Path.Combine(folder, CheckKey(photoKey) + ".jpg"), photo);
        await File.WriteAllBytesAsync(Path.Combine(folder, photoKey + "-thumb.jpg"), thumbnail);
    }

    /// <summary>A photo's path, or null if it's missing.</summary>
    public string? PhotoPath(string mapKey, string photoKey, bool thumbnail)
    {
        var path = Path.Combine(PhotoFolder(mapKey), CheckKey(photoKey) + (thumbnail ? "-thumb.jpg" : ".jpg"));
        return File.Exists(path) ? path : null;
    }

    public void DeletePhoto(string mapKey, string photoKey)
    {
        foreach (var name in new[] { CheckKey(photoKey) + ".jpg", photoKey + "-thumb.jpg" })
        {
            var path = Path.Combine(PhotoFolder(mapKey), name);
            if (File.Exists(path)) File.Delete(path);
        }
    }

    // Inside the map's folder, so deleting a map removes its photos too.
    private string PhotoFolder(string mapKey) => Path.Combine(FolderFor(mapKey), "photos");

    private static string CheckKey(string key) =>
        key.Length == 32 && key.All(Uri.IsHexDigit) ? key : throw new ArgumentException("Invalid photo key.", nameof(key));

    /// <summary>The base image's path, or null if it's missing.</summary>
    public string? BaseImagePath(string storageKey)
    {
        var path = Path.Combine(FolderFor(storageKey), BaseImageName);
        return File.Exists(path) ? path : null;
    }

    public void Delete(string storageKey)
    {
        var folder = FolderFor(storageKey);
        if (Directory.Exists(folder)) Directory.Delete(folder, recursive: true);
    }

    private string FolderFor(string storageKey)
    {
        // Keys are generated by NewStorageKey; this guards against a bad value reaching the disk.
        if (storageKey.Length != 32 || !storageKey.All(Uri.IsHexDigit))
        {
            throw new ArgumentException("Invalid map storage key.", nameof(storageKey));
        }
        return Path.Combine(_root, storageKey);
    }
}
